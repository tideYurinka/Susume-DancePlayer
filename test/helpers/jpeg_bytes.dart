import 'dart:typed_data';

/// 合成一段带 SOF0 尺寸的真实 JPEG 头部字节（测试用）：前有 APP0/DQT，
/// 便于断言「从图片自身读出比例」而不依赖真实解码。
Uint8List fakeJpegBytes({required int width, required int height}) {
  return Uint8List.fromList([
    0xFF, 0xD8, // SOI
    0xFF, 0xE0, 0x00, 0x10, // APP0，长度 16
    0x4A, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01,
    0x00, 0x00,
    0xFF, 0xDB, 0x00, 0x04, 0x00, 0x00, // DQT，长度 4
    0xFF, 0xC0, 0x00, 0x11, 0x08, // SOF0，长度 17，精度 8
    (height >> 8) & 0xFF,
    height & 0xFF,
    (width >> 8) & 0xFF,
    width & 0xFF,
    0x03, // 分量数
    0x01, 0x11, 0x00,
    0x02, 0x11, 0x01,
    0x03, 0x11, 0x01,
  ]);
}
